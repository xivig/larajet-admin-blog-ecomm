<?php

namespace App\Mail;

use Illuminate\Bus\Queueable;
use Illuminate\Contracts\Queue\ShouldQueue;
use Illuminate\Mail\Mailable;
use Illuminate\Mail\Mailables\Content;
use Illuminate\Mail\Mailables\Envelope;
use Illuminate\Queue\SerializesModels;

class AdminAlertMail extends Mailable implements ShouldQueue
{
    use Queueable, SerializesModels;

    /**
     * Create a new message instance.
     */
    public function __construct(
        public string $alertTitle,
        public string $alertMessage,
        public string $level = 'info'
    ) {
    }

    /**
     * Get the message envelope.
     */
    public function envelope(): Envelope
    {
        return new Envelope(
            subject: "[CMS Alert - " . strtoupper($this->level) . "] " . $this->alertTitle,
        );
    }

    /**
     * Get the message content definition.
     */
    public function content(): Content
    {
        return new Content(
            htmlString: "<div style='font-family: sans-serif; padding: 20px; line-height: 1.6;'>
                <h2 style='color: " . ($this->level === 'error' ? '#ef4444' : '#3b82f6') . ";'>{$this->alertTitle}</h2>
                <p>{$this->alertMessage}</p>
                <p style='color:#64748b; font-size:12px;'>Generated by CMS System at " . now()->toDateTimeString() . "</p>
            </div>"
        );
    }

    /**
     * Get the attachments for the message.
     *
     * @return array<int, \Illuminate\Mail\Mailables\Attachment>
     */
    public function attachments(): array
    {
        return [];
    }
}
